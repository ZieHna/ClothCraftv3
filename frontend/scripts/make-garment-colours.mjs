// Build-time: makes one pre-coloured picture of each garment for each colour the product is actually sold in.
//   node scripts/make-garment-colours.mjs          (from frontend/; also `npm run garments`)
//   reads   src/mocks/catalogue.json   (products, their variants' colours, the swatch of each colour)
//           public/products/<id>.webp  (the one fixed-colour photo of each garment, alpha cut-out)
//   writes  public/garments/<id>/<color>.webp   at the photo's OWN size: nothing is enlarged
//
// The algorithm is "shade-transfer", copied from the step 4a spike (spike-editor/src/tint.ts, recolour()) and ported
// from a browser canvas to raw pixels in Node. The photo's brightness ("shade": folds, seams, light and shadow) is
// measured, its typical level (the median over the solid pixels) is subtracted, and what is left is ADDED to the new
// colour. So a fold stays a fold on a dark colour, which a plain multiply cannot do. Alpha is kept as it is.
// The output is deterministic: the same inputs always give the same bytes. Fixed WebP settings, no randomness.
import { mkdir, readFile, rm, stat, writeFile } from 'node:fs/promises';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
import sharp from 'sharp';

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const catalogue = JSON.parse(await readFile(path.join(root, 'src/mocks/catalogue.json'), 'utf8'));
const swatch = new Map(catalogue.colors.map((c) => [c.id, c.hex]));
const out = path.join(root, 'public/garments');
const GAIN = 1.1; // same as the spike
const SOLID = 200; // a pixel counts as "garment" for the median when its alpha is above this

const rgb = (hex) => [1, 3, 5].map((i) => parseInt(hex.slice(i, i + 2), 16));
const luma = (r, g, b) => 0.2126 * r + 0.7152 * g + 0.0722 * b;

/** Same as the spike: the shade level that half of the solid garment pixels are below. */
function median(px) {
  const hist = new Uint32Array(256);
  let n = 0;
  for (let i = 0; i < px.length; i += 4) {
    if (px[i + 3] > SOLID) {
      hist[Math.round(luma(px[i], px[i + 1], px[i + 2]))]++;
      n++;
    }
  }
  let acc = 0;
  for (let v = 0; v < 256; v++) {
    acc += hist[v];
    if (acc >= n * 0.5) return v;
  }
  return 255;
}

function shadeTransfer(px, hex) {
  const [tr, tg, tb] = rgb(hex);
  const mid = median(px);
  const result = Buffer.from(px);
  for (let i = 0; i < result.length; i += 4) {
    if (result[i + 3] === 0) continue;
    const d = (luma(px[i], px[i + 1], px[i + 2]) - mid) * GAIN;
    result[i] = Math.max(0, Math.min(255, Math.round(tr + d)));
    result[i + 1] = Math.max(0, Math.min(255, Math.round(tg + d)));
    result[i + 2] = Math.max(0, Math.min(255, Math.round(tb + d)));
  }
  return result;
}

await rm(out, { recursive: true, force: true });
let files = 0;
let bytes = 0;
const rows = [];
for (const product of catalogue.products) {
  const colours = [...new Set(product.variants.map((v) => v.color))]; // only the colours that exist as variants
  const { data, info } = await sharp(path.join(root, 'public/products', `${product.id}.webp`))
    .ensureAlpha()
    .raw()
    .toBuffer({ resolveWithObject: true });
  await mkdir(path.join(out, product.id), { recursive: true });
  let productBytes = 0;
  for (const color of colours) {
    const hex = swatch.get(color);
    if (!hex) throw new Error(`${product.id}: colour "${color}" has no swatch in catalogue.json`);
    const file = path.join(out, product.id, `${color}.webp`);
    await sharp(shadeTransfer(data, hex), { raw: { width: info.width, height: info.height, channels: 4 } })
      .webp({ quality: 80, effort: 6, alphaQuality: 80 })
      .toFile(file);
    const size = (await stat(file)).size;
    files++;
    bytes += size;
    productBytes += size;
  }
  rows.push(`${product.id.padEnd(7)} ${String(info.width).padStart(3)}x${String(info.height).padEnd(3)} ${colours.length} colours ${(productBytes / 1024).toFixed(0).padStart(4)} KB`);
}
await writeFile(
  path.join(out, 'CREDITS.md'),
  `# Pre-coloured garment pictures

Generated by \`frontend/scripts/make-garment-colours.mjs\` (run \`npm run garments\`). One WebP per product per colour that
product is sold in, at the size of the source photo.

**Source and licence not confirmed.** Each picture is derived from the matching photo in \`public/products/\`, which came
from the v1 project's assets (\`assets-v1/\`). Their original source and licence are not recorded anywhere in this repo and
were not verified (the same open point as the T-shirt in \`public/video/CREDITS.md\`). Recolouring does not change that:
these files are derivative works. Confirm the photos may be used publicly, or replace them with garment photos you own
(then run the script again), before launch.

The recolouring itself (shade-transfer, from the step 4a spike) is original work of the project; no other source is used.
`,
);
console.log(rows.join('\n'));
console.log(`\n${files} images, ${(bytes / 1024).toFixed(0)} KB total (${(bytes / 1048576).toFixed(2)} MB)`);
